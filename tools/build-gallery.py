def build():
    items=[]
    for i,p in enumerate(sorted(PHOTO_DIR.glob('*'))):
        if p.suffix.lower() not in {'.jpg','.jpeg','.png','.webp'}: continue
        with Image.open(p) as im:
            w,h=im.size
        title,collection=CURATED.get(p.name,(f"قاب تازه {i+1}","تازه‌ها"))
        items.append({
            "id": p.stem.lower().replace('_','-'), "src": f"assets/photos/{p.name}",
            "title": title, "collection": collection, "width": w, "height": h,
            "alt": f"{title} — عکاسی علی‌اکبر"
        })
    OUT.parent.mkdir(parents=True,exist_ok=True)
    OUT.write_text(json.dumps(items,ensure_ascii=False,indent=2),encoding='utf-8')
    print(f"Wrote {len(items)} photos to {OUT}")
if __name__=='__main__': build()
